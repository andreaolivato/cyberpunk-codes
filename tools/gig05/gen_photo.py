r"""The picture Trauma Team sends with the job ad: a texture, a one-part
atlas and two icon records.

    python tools\gig05\gen_photo.py

Reads   source\gui\<name>.png               each photo, committed like a WAV master
Writes  raw\mod\trauma_team\gui\<name>.xbm            the texture (binary)
        raw\mod\trauma_team\gui\<name>.inkatlas.json  the atlas, one part
        source\tweaks\photo.yaml                      the icon records

GIG 03'S TOOL, for more than one picture (tools/gig03/gen_photo.py): its
header carries the measurements, how a message shows a picture, the UI
texture flags and the atlas shape. The atlas shape file is read from
tools/gig03.

THE PICTURES are photo-mode shots taken in a desk playtest on 2026-11-03,
cropped to gig 03's 1000x563: the AV on the Medical Center's roof with its
crew (`av`). The design call, 2026-11-04: this one, the crew at the door was bad.

Run by hand when a PNG changes; the xbm it writes is committed and ships.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from gig05_config import SOURCE, RAW_MOD, DEPOT                     # noqa: E402

WK = os.path.expandvars(r'%LOCALAPPDATA%\Programs\WolvenKit.CLI\WolvenKit.CLI.exe')
B = chr(92)
GUI_OUT = os.path.join(RAW_MOD, 'gui')
TWEAK_OUT = os.path.join(SOURCE, 'tweaks', 'photo.yaml')

# (picture, icon record); the message that shows each is in gen_journal.py.
PHOTOS = [('av', 'UIJournalIcons.cc_g05_av')]


def run(args):
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit('%s\n%s' % (' '.join(args), r.stdout + r.stderr))
    return r.stdout


def import_texture(name):
    png = os.path.join(SOURCE, 'gui', name + '.png')
    if not os.path.exists(png):
        raise SystemExit('no picture at %s' % png)
    tmp = tempfile.mkdtemp(prefix='cc-g05-photo-')
    run([WK, 'import', png, '-o', tmp])
    xbm = os.path.join(tmp, name + '.xbm')
    # Serialize, set the UI flags, deserialize.
    run([WK, 'convert', 'serialize', xbm, '-o', tmp])
    jpath = xbm + '.json'
    with open(jpath, encoding='utf-8') as fh:
        doc = json.load(fh)
    setup = doc['Data']['RootChunk']['setup']
    setup['group'] = 'TEXG_Generic_UI'
    setup['isGamma'] = 1
    setup['isStreamable'] = 0
    setup['allowTextureDowngrade'] = 1
    with open(jpath, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(doc, fh, indent=1)
    os.remove(xbm)
    run([WK, 'convert', 'deserialize', jpath, '-o', tmp])
    if not os.path.exists(xbm):
        raise SystemExit('deserialize produced no xbm in %s' % tmp)
    os.makedirs(GUI_OUT, exist_ok=True)
    out = os.path.join(GUI_OUT, name + '.xbm')
    shutil.copyfile(xbm, out)
    w, h = doc['Data']['RootChunk']['width'], doc['Data']['RootChunk']['height']
    shutil.rmtree(tmp, ignore_errors=True)
    print('wrote %s (%dx%d)' % (out, w, h))


def resref(path):
    return {'DepotPath': {'$type': 'ResourcePath', '$storage': 'string',
                          '$value': path}, 'Flags': 'Soft'}


def part(name):
    return {'$type': 'inkTextureAtlasMapper',
            'clippingRectInPixels': {'$type': 'Rect', 'bottom': 0, 'left': 0,
                                     'right': 0, 'top': 0},
            'clippingRectInUVCoords': {'$type': 'RectF', 'Bottom': 1.0,
                                       'Left': 0.0, 'Right': 1.0, 'Top': 0.0},
            'partName': {'$type': 'CName', '$storage': 'string',
                         '$value': name}}


def write_atlas(name):
    here = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'gig03')
    with open(os.path.join(here, 'vanilla_inkatlas_shape.json'), encoding='utf-8') as fh:
        doc = json.load(fh)
    first = doc['Data']['RootChunk']['slots']['Elements'][0]
    first['texture'] = resref(DEPOT + B + 'gui' + B + name + '.xbm')
    first['parts'] = [part(name)]
    out = os.path.join(GUI_OUT, name + '.inkatlas.json')
    with open(out, 'w', encoding='utf-8', newline=chr(10)) as fh:
        json.dump(doc, fh, indent=2)
    print('wrote', out)


def write_tweak():
    lines = [
        '# THE PICTURES TRAUMA TEAM SENDS with the job ad, each as two icon records:',
        '# the one a message names through `imageId`, and its `_full` twin for the',
        '# enlarged view. Generated by tools/gig05/gen_photo.py, which also makes',
        '# the textures and the atlases they point at.',
        '',
    ]
    for name, record in PHOTOS:
        atlas = DEPOT + B + 'gui' + B + name + '.inkatlas'
        for rec in (record, record + '_full'):
            lines += [rec + ':', '  $type: UIIcon', '  atlasResourcePath: ' + atlas,
                      '  atlasPartName: ' + name]
    lines.append('')
    with open(TWEAK_OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(chr(10).join(lines))
    print('wrote', TWEAK_OUT)


if __name__ == '__main__':
    for name, _record in PHOTOS:
        import_texture(name)
        write_atlas(name)
    write_tweak()
